export const launches = activeProducts
  .filter((p) => p.isLaunch)
  .sort((a, b) => a.order - b.order);

export const featured = activeProducts
  .filter((p) => p.isFeatured)
  .sort((a, b) => a.order - b.order);

export function getProduct(slug: string) {
  return activeProducts.find((p) => p.slug === slug);
}

export function getRelated(product: Product, limit = 4) {
  const related = (product.relatedSlugs ?? [])
    .map((slug) => getProduct(slug))
    .filter((p): p is Product => Boolean(p));
  if (related.length < limit) {
    const extra = activeProducts.filter(
      (p) =>
        p.category === product.category &&
        p.slug !== product.slug &&
        !related.includes(p),
    );
    related.push(...extra.slice(0, limit - related.length));
  }
  return related.slice(0, limit);
}

